//! LLVM IR backend for Sun's initial scalar subset.
use std::collections::HashMap;
use sun_ast::{BinaryOp, Expr, ExprKind, Module, StmtKind, UnaryOp};
use thiserror::Error;
#[derive(Debug, Error)]
pub enum BackendError {
    #[error("unsupported construct for native compilation: {0}")]
    Unsupported(String),
    #[error("undefined variable '{0}'")]
    UndefinedVariable(String),
}
#[derive(Default)]
struct Generator { next_value: usize, variables: HashMap<String, String>, body: Vec<String> }
impl Generator {
    fn value(&mut self) -> String { let name = format!("%v{}", self.next_value); self.next_value += 1; name }
    fn expression(&mut self, expr: &Expr) -> Result<String, BackendError> {
        match &expr.kind {
            ExprKind::Number(number) => Ok(format!("{:.17e}", number)),
            ExprKind::Identifier(name) => self.variables.get(name).cloned().ok_or_else(|| BackendError::UndefinedVariable(name.clone())),
            ExprKind::Unary { op, operand } => {
                let value = self.expression(operand)?;
                match op {
                    UnaryOp::Positive => Ok(value),
                    UnaryOp::Negative => { let result=self.value(); self.body.push(format!("  {result} = fneg double {value}")); Ok(result) }
                    UnaryOp::Not => Err(BackendError::Unsupported("logical negation".into())),
                }
            }
            ExprKind::Binary { left, op, right } => {
                let lhs=self.expression(left)?; let rhs=self.expression(right)?;
                let instruction=match op {
                    BinaryOp::Add=>"fadd", BinaryOp::Subtract=>"fsub",
                    BinaryOp::Multiply|BinaryOp::ElementMultiply=>"fmul",
                    BinaryOp::Divide|BinaryOp::ElementDivide=>"fdiv",
                    BinaryOp::Power=>return Err(BackendError::Unsupported("power operator".into())),
                    _=>return Err(BackendError::Unsupported(format!("operator {op:?}"))),
                };
                let result=self.value(); self.body.push(format!("  {result} = {instruction} double {lhs}, {rhs}")); Ok(result)
            }
            ExprKind::Call { callee, arguments } => {
                if !matches!(&callee.kind, ExprKind::Identifier(name) if name=="disp") || arguments.len()!=1 {
                    return Err(BackendError::Unsupported("only disp(expression) calls are supported".into()));
                }
                let value=self.expression(&arguments[0])?; self.print(&value); Ok(value)
            }
            ExprKind::String(_) => Err(BackendError::Unsupported("string literals".into())),
            ExprKind::Matrix(_) => Err(BackendError::Unsupported("matrix literals (planned for the matrix codegen milestone)".into())),
        }
    }
    fn print(&mut self, value:&str) { self.body.push(format!("  call i32 (ptr, ...) @printf(ptr @.sun_fmt, double {value})")); }
}
pub fn compile_to_llvm_ir(module:&Module)->Result<String,BackendError>{
    let mut generator=Generator::default();
    for statement in &module.statements {
        match &statement.kind {
            StmtKind::Assign{name,value}=>{let result=generator.expression(value)?;generator.variables.insert(name.clone(),result);}
            StmtKind::Expr(expr)=>{
                let result=generator.expression(expr)?;
                let is_disp=matches!(&expr.kind,ExprKind::Call{callee,..} if matches!(&callee.kind,ExprKind::Identifier(name) if name=="disp"));
                if !statement.suppress_output && !is_disp { generator.print(&result); }
            }
        }
    }
    let mut ir=String::from("; Generated by the Sun compiler\n@.sun_fmt = private unnamed_addr constant [4 x i8] c\"%g\\0A\\00\"\ndeclare i32 @printf(ptr, ...)\n\ndefine i32 @main() {\nentry:\n");
    for instruction in generator.body {ir.push_str(&instruction);ir.push('\n');}
    ir.push_str("  ret i32 0\n}\n"); Ok(ir)
}
#[cfg(test)]
mod tests {
    use super::*; use sun_parser::parse;
    #[test] fn emits_arithmetic_and_prints_unsuppressed_expressions(){
        let ast=parse("x = 2 + 3 * 4;\ndisp(x);\n2 + 2").unwrap();
        let ir=compile_to_llvm_ir(&ast).unwrap();
        assert!(ir.contains("fmul double")); assert!(ir.contains("fadd double"));
        assert_eq!(ir.matches("@printf").count(),3);
    }
    #[test] fn rejects_matrix_literals_with_a_clear_error(){
        let ast=parse("A = [1, 2; 3, 4];").unwrap();
        assert!(compile_to_llvm_ir(&ast).unwrap_err().to_string().contains("matrix literals"));
    }
}
